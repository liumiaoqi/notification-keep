    fun isOp(event: String): Boolean = event in ALL

    /** 导出文件里那一行的标识（核对时要按它找） */
    const val SELF_HASH_KEY = "exportSelfHash"

    private const val MARKER = "\"$SELF_HASH_KEY\":\""

    /**
     * **导出文件自身的 hash** —— 对"**除最后一行之外**"的全部内容求 SHA-256。
     *
     * 为什么要排除最后一行：如果把自己的 hash 也算进去，就是**自指**（算不出来）
     *   => 约定：自 hash 作为**文件的最后一行**，核对时去掉它再算
     */
    fun selfHashOf(bodyWithoutLastLine: String): String =
        HashChain.sha256(bodyWithoutLastLine)

    /**
     * **核对**：给定完整导出文本，重算并比对最后一行里声明的自 hash
     *
     * @return true = "手上这份文件就是当时导出的那一份"
     */
    fun verifyExportSelfHash(fullText: String): Boolean {
        val lines = fullText.trimEnd('\n').split('\n')
        if (lines.isEmpty()) return false
        val last = lines.last()
        val i = last.indexOf(MARKER)
        if (i < 0) return false
        val claimed = last.substring(i + MARKER.length).substringBefore('"')
        if (claimed.isEmpty()) return false
        val recomputed = selfHashOf(lines.dropLast(1).joinToString("\n"))
        return claimed == recomputed
    }
