/**
 ***JSON 转义的写侧一半**（它与核对器 `verify_export.py` 的读侧**成对**）
 *
 * 2026-09-28：从 `NotifStore` 的**私有实例方法**搬成【顶层函数】（工程化重构第二刀）
 *   而这次搬迁顺手修掉了一处**伪依赖**：
 *     它原来是 `NotifStore` 的**实例方法**，而它**不引用任何实例字段**
 *       （`tools/cohesion_matrix.py` 的输出就是这么写的：它在"不引用实例字段"那一组）
 *       =>即：它**假装**自己需要一个 `NotifStore` 实例
 *         => 而后果是**具体的**：JVM 单测里造不出 `NotifStore`（那要 `Context`）
 *           => **所以它一条测试都没有**（实测：全仓 0 条）
 *         =>搬成顶层函数之后 => **纯 JVM 可测**（见 `EscGoldenTest`）
 *
 ***契约：它是跨语言的一半 => 别改一个字符**
 *   判据来源：独立复核者的第二条 caveat ——
 *     「`esc` 是跨语言契约的一半 => 原样搬、别改一个字符」
 *   => 改一个字符 => **接收方的核对器会判"文件被改过"**
 *     （而那是本工具最不能出的假警报 —— 它会教用户不相信那个警报）
 *
 * 转义规则（与读侧成对）：
 *   1 `"` `\` => 加反斜杠
 *   2 LF CR TAB => 短形式（`\n` `\r` `\t`）
 *   3 其余 code < 0x20 => `\uXXXX`（含 **U+0001** —— 它是哈希链的字段分隔符）
 *   4 **U+0085 U+2028 U+2029** => `\uXXXX`
 *     这三个是 A9（2026-09-28）补的：它们在 JSON 里**合法**、
 *        却会让 Python 的 `str.splitlines()` **断行** => 核对器把一行读成两行
 *        => 判"文件被改过"（狼来了）
 *   5 其余字符（含中文）=> **原样**
 */
internal fun esc(s: String): String = buildString {
    for (ch in s) when (ch) {
        '"' -> append("\\\""); '\\' -> append("\\\\")
        '\n' -> append("\\n"); '\r' -> append("\\r"); '\t' -> append("\\t")
        //2026-09-28 修（A9 写侧）：**额外转义三个"会断行的"字符**
        //   改前只转义 code < 0x20 => U+0085 / U+2028 / U+2029 **原样落进文件**
        //   而它们在 JSON 里是合法字符、**却在 str.splitlines() 上会断行**
        //   => 打包发出的 Python 核对器读一行会读成两行 => 判"文件被改过"（狼来了）
        //   => 转义成 \uXXXX 是 **JSON 标准转义** => 接收方解析回来仍是原字符
        //   （与读侧那条同时生效：这里净化【新的】导出，读侧兼容【旧的】导出）
        else -> if (ch.code < 0x20 || ch.code == 0x85 ||
                    ch.code == 0x2028 || ch.code == 0x2029) {
            append("\\u%04x".format(ch.code))
        } else append(ch)
    }
}
